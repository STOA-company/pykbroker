"""Broker-neutral synchronous contracts, independent of vendor SDKs."""

from collections.abc import Callable
from datetime import date, datetime
from typing import Protocol, runtime_checkable

from .models import Balance, CancelRequest, Capabilities, Order, OrderRequest, Position, Quote, Rules


@runtime_checkable
class StockBroker(Protocol):
    broker_code: str

    def get_quote(self, symbol: str, *, market: str = "KR") -> Quote: ...
    def get_balance(self) -> Balance: ...
    def get_positions(self) -> list[Position]: ...
    def list_orders(self, symbol: str | None = None) -> list[Order]: ...
    def get_rules(
        self, symbol: str, *, now: datetime | None = None, trading_day: Callable[[date], bool] | None = None
    ) -> Rules: ...
    def capabilities(self) -> Capabilities: ...
    def place_order(self, request: OrderRequest) -> Order: ...
    def cancel_order(self, request: CancelRequest) -> Order: ...
    def close(self) -> None: ...


@runtime_checkable
class BrokerAdapter(StockBroker, Protocol):
    """Narrow execution-facing vocabulary over the same typed contract."""

    def quote(self, symbol: str, *, market: str = "KR") -> Quote: ...
    def balance(self) -> Balance: ...
    def positions(self) -> list[Position]: ...
    def rules(
        self, symbol: str, *, now: datetime | None = None, trading_day: Callable[[date], bool] | None = None
    ) -> Rules: ...
    def place(self, request: OrderRequest) -> Order: ...
    def cancel(self, request: CancelRequest) -> Order: ...
    def status(self, order: Order) -> Order: ...
